#!/bin/bash
# =============================================================================
# STEP 4: Multi-seed evaluation of the ablation models on eval v2
# =============================================================================
# Auto-detects available checkpoints from the filesystem (since checkpoint
# numbers depend on how long training ran), generates eval YAMLs, then
# evaluates with the same 3-seed protocol as step 2.
#
# Prerequisites:
#   - Step 1 complete (tphage/BeamRL-EvalData-v2 uploaded)
#   - Step 3 complete (ablation models trained; checkpoints on disk)
#
# Run from: BeamPERL/BeamRL/
#   bash scripts/experiments/step4_eval_ablations.sh
#
# To evaluate only one ablation:
#   bash scripts/experiments/step4_eval_ablations.sh format_only
#   bash scripts/experiments/step4_eval_ablations.sh accuracy_only
# =============================================================================

set -euo pipefail

SCRIPT_DIR="$(cd "$(dirname "${BASH_SOURCE[0]}")" && pwd)"
BEAMRL_DIR="$(cd "${SCRIPT_DIR}/../.." && pwd)"

WHICH="${1:-both}"

echo "============================================================"
echo "STEP 4: Multi-seed eval — ablation models (v2 dataset)"
echo "Target: ${WHICH}"
echo "Started: $(date)"
echo "============================================================"

cd "${BEAMRL_DIR}"
source "./setup/set_vars.sh"

ADAPTER_TYPE="grpo_beamrl_train"
MODEL_NAME="DeepSeek-R1-Distill-Qwen-1.5B"

# Generates a temporary eval YAML for an ablation model and runs the eval script.
eval_ablation() {
    local ablation_name="$1"   # e.g. "beamrl_format_only"
    local friendly_name="$2"   # e.g. "format_only"

    local ckpt_model_dir="${CKPT_DIR}/models/${MODEL_NAME}/${ADAPTER_TYPE}/${ablation_name}"
    if [ ! -d "${ckpt_model_dir}" ]; then
        echo "ERROR: Checkpoint directory not found: ${ckpt_model_dir}"
        echo "Did step 3 (training) complete for ${ablation_name}?"
        return 1
    fi

    # Auto-detect available checkpoints by listing dirs named checkpoint-*
    CKPT_LIST=()
    while IFS= read -r -d '' ckpt_dir; do
        ckpt_name="$(basename "${ckpt_dir}")"
        # Skip -merged directories (those are already merged, not adapter dirs)
        if [[ "${ckpt_name}" != *"-merged" ]]; then
            CKPT_LIST+=("${ckpt_name}")
        fi
    done < <(find "${ckpt_model_dir}" -maxdepth 1 -type d -name "checkpoint-*" -print0 | sort -z -V)

    if [ ${#CKPT_LIST[@]} -eq 0 ]; then
        echo "ERROR: No checkpoints found in ${ckpt_model_dir}"
        return 1
    fi

    echo ""
    echo "------------------------------------------------------------"
    echo "Evaluating ablation: ${ablation_name}"
    echo "Checkpoints found:   ${CKPT_LIST[*]}"
    echo "Start: $(date)"
    echo "------------------------------------------------------------"

    # Write a temporary eval YAML with the detected checkpoints
    local tmp_yaml="${BEAMRL_DIR}/recipes/eval_model_${ablation_name}_tmp.yaml"
    cat > "${tmp_yaml}" <<YAML_EOF
# Auto-generated by step4_eval_ablations.sh — safe to delete after eval
model_name: ${MODEL_NAME}
pt_type: grpo
pt_config_name: ${ablation_name}
pt_dataset_name: beamrl_train
save_name: ${ablation_name}

checkpoints:
$(printf "  - %s\n" "${CKPT_LIST[@]}")

max_model_length: 32768
eval_dataset_name: beamrl_eval_v2
eval_dataset_config: null
eval_split: train
max_prompt_length: 512
max_generation_length: 4096
batch_size: 4
num_generations: 7
temperature: 0.6
max_model_len: 32768
gpu_memory_utilization: 0.7
dtype: bfloat16
log_wandb: true
wandb_project: beamrl-eval-v2-ablation
max_eval_samples: null
YAML_EOF

    echo "Generated eval config: ${tmp_yaml}"

    export EVAL_SEEDS="${EVAL_SEEDS:-42 123 456}"
    bash scripts/eval/eval_model_beamrl.sh "${tmp_yaml}"

    # Clean up temp YAML
    rm -f "${tmp_yaml}"
    echo "Evaluation complete for ${ablation_name}: $(date)"
}

if [[ "${WHICH}" == "format_only" || "${WHICH}" == "both" ]]; then
    eval_ablation "beamrl_format_only" "format_only"
fi

if [[ "${WHICH}" == "accuracy_only" || "${WHICH}" == "both" ]]; then
    eval_ablation "beamrl_accuracy_only" "accuracy_only"
fi

echo ""
echo "============================================================"
echo "STEP 4 COMPLETE: $(date)"
echo "Results in: ${OUTPUT_DIR}/beamrl_eval/{seed}/"
echo "Proceed to step5_aggregate.sh"
echo "============================================================"
